<h2>2. What we process and why</h2>

<h3>Football school enrolment form</h3>
<ul>
    <li><strong>Data:</strong> the child’s name and surname, year of birth, the parent’s/guardian’s name and surname, phone number, email (optional), preferred age group (optional) and a note (optional).</li>
    <li><strong>Purpose:</strong> to contact you about enrolment and a trial training.</li>
    <li><strong>Legal basis:</strong> the consent of the parent/guardian, given by ticking the box before sending, and steps taken at your request before entering a membership/training agreement.</li>
    <li><strong>Retention:</strong> until the enrolment is completed or declined; if the child is not enrolled we delete the application within 12 months of receipt at the latest. For enrolled children, data is kept in the club’s records under a separate agreement and applicable law.</li>
    <li>If you enter an email address, we send a confirmation of receipt.</li>
</ul>

<h3>Contact form</h3>
<ul>
    <li><strong>Data:</strong> name, email, phone (optional), subject (optional) and your message.</li>
    <li><strong>Purpose:</strong> to answer your question.</li>
    <li><strong>Legal basis:</strong> the club’s legitimate interest and your interest in receiving a reply.</li>
    <li><strong>Retention:</strong> up to 12 months after the last correspondence.</li>
</ul>

<h3>Supporting the club (donations)</h3>
<p>The website does not accept payments and does not collect card data. It only shows the club’s bank details; you pay through your own bank. We process data about payments received on the club’s account to the extent and for the periods required by law (accounting and tax rules).</p>

<h3>Technical data</h3>
<p>When you visit, the server automatically records your IP address, request time, requested address and browser type. These logs are used to run and secure the website (protection from abuse and overload), are processed on the basis of legitimate interest and kept for 30 days at most. We use no analytics or advertising tools.</p>

<h2>3. Children</h2>
<p>The enrolment form is filled in by a parent or guardian, not by the child. Persons under 15 cannot give consent on their own for information society services, so we do not collect data from them directly. We do not ask for photographs, personal ID numbers or health data through the website. Photos and videos of children are published only with the consent of a parent/guardian.</p>

<h2>4. Cookies</h2>
<p>The website uses only strictly necessary cookies (session and form protection), which expire when you close the browser or the session ends; no consent is needed for them. We do not use cookies for analytics, tracking or advertising.</p>

<h2>5. Third-party services</h2>
<ul>
    <li><strong>Google Fonts:</strong> fonts are loaded from Google servers, so Google receives your IP address.</li>
    <li><strong>YouTube and Vimeo:</strong> videos and live streams are embedded from these services (YouTube in “youtube-nocookie” mode). These providers may collect device and IP data when you play or open a video; their own privacy policies apply.</li>
    <li><strong>Social networks:</strong> links to the club’s profiles lead to third-party sites with their own rules.</li>
    <li><strong>Hosting and email:</strong> we use hosting and email providers that process data only on our behalf.</li>
</ul>
<p>Some of these providers have servers outside Serbia (e.g. in the USA or the EU). Transfers are made with the safeguards required by law. We do not sell data or share it for marketing.</p>

<h2>6. Who has access</h2>
<p>Applications and messages are seen only by authorised club staff and coaches who need them for their work, through the protected admin area of the website.</p>

<h2>7. Your rights</h2>
<p>You have the right to request information about processing, access to and a copy of your data, rectification, erasure, restriction of processing, data portability, to object to processing and to withdraw consent at any time (withdrawal does not affect processing before it). Send your request by email; we reply within 30 days, which may be extended as the law allows.</p>
<p>If you believe your data is processed contrary to the law, you may lodge a complaint with the Commissioner for Information of Public Importance and Personal Data Protection (<a href="https://www.poverenik.rs" target="_blank" rel="noopener">www.poverenik.rs</a>).</p>

<h2>8. Security</h2>
<p>We use an encrypted connection (HTTPS), admin access protected by accounts and limited by role, and protection of forms against automated abuse.</p>

<h2>9. Changes</h2>
<p>We may change this policy. The current version is always this page, with the date of the last update.</p>
