<h2>5. Podrška klubu</h2>
<p>Sajt ne prima uplate. Podrška klubu je dobrovoljna uplata na račun kluba preko vaše banke. Uplata se ne može smatrati ugovorom o kupovini niti daje pravo na protivuslugu. Uplaćeni iznos klub ne vraća osim u slučaju očigledne greške u uplati. Poreske olakšice za davaoca zavise od važećih propisa i njegovog statusa; za savet se obratite poreskom savetniku.</p>

