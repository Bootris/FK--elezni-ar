<p>Ova politika objašnjava koje podatke o ličnosti FK Železničar Niš (u daljem tekstu: „klub“, „mi“) prikuplja preko ovog sajta, zašto, na kom pravnom osnovu, koliko dugo ih čuva i koja prava imate. Pisana je u skladu sa Zakonom o zaštiti podataka o ličnosti Republike Srbije („Sl. glasnik RS“, br. 87/2018).</p>

<h2>1. Ko je rukovalac podacima</h2>
