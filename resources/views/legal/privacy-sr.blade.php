<p>Za sva pitanja o zaštiti podataka, kao i za ostvarivanje prava, pišite na gornju imejl adresu.</p>

<h2>2. Koje podatke obrađujemo i zašto</h2>

<h3>Prijava za upis u školu fudbala</h3>
<ul>
    <li><strong>Podaci:</strong> ime i prezime deteta, godina rođenja, ime i prezime roditelja/staratelja, telefon, imejl (opciono), željena selekcija (opciono) i napomena (opciono).</li>
    <li><strong>Svrha:</strong> da vas kontaktiramo u vezi sa upisom i probnim treningom.</li>
    <li><strong>Pravni osnov:</strong> saglasnost roditelja/staratelja koju dajete označavanjem polja pre slanja prijave, odnosno radnje preduzete na vaš zahtev pre zaključenja ugovora o članstvu/treniranju.</li>
    <li><strong>Rok čuvanja:</strong> dok se upis ne završi ili odbije; ako dete ne bude upisano, prijavu brišemo najkasnije 12 meseci od prijema. Za upisanu decu, podaci se vode u evidenciji kluba u skladu sa posebnim ugovorom i propisima.</li>
    <li>Ako unesete imejl adresu, poslaćemo vam potvrdu prijema.</li>
</ul>

<h3>Kontakt forma</h3>
<ul>
    <li><strong>Podaci:</strong> ime, imejl, telefon (opciono), tema (opciono) i sadržaj poruke.</li>
    <li><strong>Svrha:</strong> da odgovorimo na vaše pitanje.</li>
    <li><strong>Pravni osnov:</strong> legitimni interes kluba i vaš interes da dobijete odgovor.</li>
    <li><strong>Rok čuvanja:</strong> do 12 meseci od poslednje prepiske.</li>
</ul>

<h3>Podrška klubu (donacije)</h3>
<p>Sajt ne prima uplate i ne prikuplja podatke o platnim karticama. Prikazuju se samo podaci računa kluba; uplatu vršite u svojoj banci. Podatke o uplatama koje klub primi na račun obrađujemo u meri i rokovima koje propisuje zakon (računovodstvo i poresko poslovanje).</p>

<h3>Tehnički podaci</h3>
<p>Prilikom posete server automatski beleži IP adresu, vreme zahteva, traženu adresu i vrstu pregledača. Ovi zapisi služe za rad i bezbednost sajta (zaštita od zloupotrebe i preopterećenja), obrađuju se na osnovu legitimnog interesa i čuvaju se najviše 30 dana. Ne koristimo analitiku ni reklamne alate.</p>

<h2>3. Deca</h2>
<p>Prijavu za upis popunjava roditelj ili staratelj, a ne dete. Lica mlađa od 15 godina ne mogu samostalno da daju saglasnost u vezi sa uslugama informacionog društva, zato od njih ne prikupljamo podatke direktno. Ne tražimo fotografije, matični broj ni zdravstvene podatke kroz sajt. Fotografije i snimke dece objavljujemo samo uz saglasnost roditelja/staratelja.</p>

<h2>4. Kolačići i slični alati</h2>
<p>Sajt koristi samo tehnički neophodne kolačiće (sesija i zaštita formi od zloupotrebe) koji se brišu zatvaranjem pregledača ili istekom sesije; za njih nije potrebna saglasnost. Ne koristimo kolačiće za analitiku, praćenje ni oglašavanje.</p>

<h2>5. Servisi trećih strana</h2>
<ul>
    <li><strong>Google Fonts:</strong> fontovi se učitavaju sa Google servera, pri čemu Google dobija vašu IP adresu.</li>
    <li><strong>YouTube i Vimeo:</strong> video snimci i prenosi su ugrađeni sa ovih servisa (YouTube u režimu „youtube-nocookie“). Ti provajderi mogu prikupljati podatke o vašem uređaju i IP adresi kada pokrenete ili otvorite snimak; primenjuju se njihove politike privatnosti.</li>
    <li><strong>Društvene mreže:</strong> linkovi ka profilima kluba vode na sajtove trećih lica koji imaju sopstvena pravila.</li>
    <li><strong>Hosting i imejl:</strong> koristimo provajdere hostinga i slanja imejla koji podatke obrađuju samo po našem nalogu.</li>
</ul>
<p>Neki od ovih provajdera imaju servere van Srbije (npr. u SAD ili EU). Prenos se vrši uz mere zaštite predviđene zakonom. Podatke ne prodajemo niti ih ustupamo radi marketinga.</p>

<h2>6. Ko ima pristup podacima</h2>
<p>Prijave i poruke vide samo ovlašćeni radnici i treneri kluba kojima su potrebni za rad, kroz zaštićeni administrativni deo sajta.</p>

<h2>7. Vaša prava</h2>
<p>Imate pravo da zatražite informaciju o obradi, pristup podacima i kopiju, ispravku, brisanje, ograničenje obrade, prenosivost podataka, kao i da uložite prigovor na obradu i opozovete saglasnost u bilo kom trenutku (opoziv ne utiče na zakonitost obrade pre opoziva). Zahtev šaljite imejlom; odgovaramo u roku od 30 dana, koji se u skladu sa zakonom može produžiti.</p>
<p>Ako smatrate da se vaši podaci obrađuju protivno zakonu, možete podneti pritužbu Povereniku za informacije od javnog značaja i zaštitu podataka o ličnosti (<a href="https://www.poverenik.rs" target="_blank" rel="noopener">www.poverenik.rs</a>).</p>

<h2>8. Bezbednost</h2>
<p>Koristimo šifrovanu vezu (HTTPS), pristup administraciji zaštićen nalogom, ograničen po ulozi, i zaštitu formi od automatizovanih zloupotreba.</p>

<h2>9. Izmene politike</h2>
<p>Politiku možemo izmeniti. Važeća verzija je uvek ova stranica, sa datumom poslednje izmene.</p>
